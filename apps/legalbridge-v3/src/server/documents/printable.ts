/**
 * PDF に刷る前に、フォントに無い字を刷れる字に置き換える。
 *
 * PDF を作るサーバのフォントは Noto CJK だけ（Dockerfile の font-noto-cjk）。
 * そこに無い字はフォールバック先も無く、□に×（☒）で刷られる。住所の
 * ハイフンでよく起きる。取引先の住所を Excel・CSV・他システムから写したとき、
 * 見た目はハイフンでも中身が珍しい字になっていることがある。
 *   ・U+0096 / U+0097 … Windows-1252 の – — を Latin-1 として読んだ制御文字
 *   ・U+2043（⁃）・U+02D7（˗）・U+FE58（﹘）… ハイフンに似た記号
 * ブラウザの画面では別のフォントが拾って普通に見えるので、紙にして初めて気づく。
 * 元のデータはそのまま（直すなら取引先の画面で）。刷るときだけ揃える。
 */

/** Windows-1252 の 0x80–0x9F を本来の字に戻す（Latin-1 として読まれた制御文字）。 */
const CP1252: Record<number, string> = {
  0x80: "€", 0x85: "…", 0x91: "‘", 0x92: "’", 0x93: "“", 0x94: "”",
  0x95: "・", 0x96: "‐", 0x97: "—", 0x99: "™"
};

/** ハイフンに似ているが Noto CJK に無い字。 */
const HYPHEN_LIKE = /[⁃˗﹘⸺⸻]/g;

export function printableText(html: string): string {
  return html
    .replace(HYPHEN_LIKE, "‐")
    // C1 制御文字。対応のあるものは戻し、無いものは消す（刷っても☒になるだけ）。
    .replace(/[\u0080-\u009F]/g, (ch) => CP1252[ch.charCodeAt(0)] ?? "")
    // C0 制御文字（改行・タブ・復帰以外）も刷れない。
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, "");
}
